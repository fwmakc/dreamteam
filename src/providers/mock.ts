/** mock-провайдер не знает, кто из агентов спрашивает — узнаём коллегу по системному промпту */
const NAME_TO_ID: Record<string, string> = {
  'марина': 'marina',
  'дмитрий': 'dmitry',
  'алиса': 'alisa',
  'сергей': 'sergey',
  'виктор': 'viktor',
};

function pickReply(req: StreamRequest): string {
  const system = (req.system ?? '').toLowerCase().replace(/ё/g, 'е');
  let agentId: string | undefined;
  for (const [name, id] of Object.entries(NAME_TO_ID)) {
    if (system.includes(`ты — ${name}`)) {
      agentId = id;
      break;
    }
  }
  const variants = (agentId && CANNED[agentId]) || GENERIC;
  return variants[req.messages.length % variants.length];
}

/** Mock-провайдер: печатает заготовленный ответ «по слову», как настоящий стрим. */
export class MockProvider implements LLMProvider {
  readonly kind = 'mock';

  constructor(
    readonly id: string,
    readonly model = 'mock',
    private readonly fixedReply?: string,
    private readonly delayMs = 20,
  ) {}

  async *stream(req: StreamRequest, onUsage?: (usage: RoundUsage) => void): AsyncGenerator<string> {
    let text = this.fixedReply ?? pickReply(req);
    // демо менеджера переговорки: приветствие нового разговора — без действий
    if (!this.fixedReply && (req.system ?? '').startsWith('Ты — менеджер переговорки')) {
      const first = req.messages[0]?.content ?? '';
      if (first.includes('Поприветствуй')) {
        text =
          'Добрый день! Я менеджер переговорки — начнём один на один. Скажите, что нужно, а я сделаю: ' +
          'позову участников из команды в этот чат, включу кому-нибудь инструменты, заведу проект с серверами ' +
          'или открою другой разговор. Например: «позови Марину и Дмитрия» или «включи Глебу shell».';
      } else {
        // Ключи — по последней просьбе руководителя, но история менеджера
        // эхом повторяет прошлые просьбы, поэтому проверяем от частного к
        // общему: «статус команды» — финальный ответ без действий, «позови
        // Теста в чат» — demo chat.add, дальше «Тест» уже в команде (id
        // виден в стейте) — не дублируем, иначе детерминированно зовём его
        // с тулами files+shell для демо-ступенек.
        const wantsStatus = first.includes('статус команды');
        const wantsInChat = first.includes('позови Теста в чат');
        const hasTest = first.includes('test_probe');
        text = wantsStatus
          ? 'Команда на месте: дубликатов нет, все на связи.'
          : wantsInChat
            ? '{"say":"Зову Теста в этот чат.","actions":[{"op":"chat.add","who":"Тест"}]}'
            : hasTest
              ? '«Тест» уже в команде — второй раз не дублирую.'
              : '{"say":"Позываю нового участника «Тест».","actions":[{"op":"team.add","id":"test_probe","name":"Тест","role":"гость","prompt":"Ты — Тест, гость переговорки. Отвечай коротко.","emoji":"🧪","color":"cyan","tools":{"files":{},"shell":{}}}]}';
      }
    } else if (!this.fixedReply && req.messages.some((m) => m.images?.length)) {
      // mock-зрение: запрос с картинкой — это инструмент look, отвечаем заготовленным разбором
      text =
        'Смотрю на изображение: тёмно-синяя шапка с логотипом слева, под ней крупный светлый заголовок ' +
        'и градиентная кнопка по центру. Ниже три карточки с тонкими рамками и подписями. ' +
        'Стиль — плоский минимализм, шрифт без засечек.';
    } else if (!this.fixedReply && (req.system ?? '').includes('```image')) {
      // демо художника: генерация → look на свой файл → итог. Детерминировано для тестов.
      const steps = req.messages.filter((m) => m.content.includes('⚙ Результаты твоих действий')).length;
      if (steps === 0) {
        text =
          'Принесла первые наброски — четыре варианта в маленьком разрешении, дёшево и сердито:\n' +
          '```image\nprompt: poster sketch, minimal flat style, deep blue palette, high contrast\nsize: 512x768\nn: 4\n```\n' +
          'Сейчас сама посмотрю, что вышло, и покажу вам.';
      } else if (steps === 1) {
        const lastTool = [...req.messages]
          .reverse()
          .find((m) => m.content.includes('⚙ Результаты твоих действий'));
        const path =
          lastTool?.content.match(/[\w./\\-]*images[/\\][\w./\\-]+\.(?:png|jpe?g|webp)/i)?.[0] ??
          'images/sketch-1.png';
        text =
          'Проверю глазами, что там сгенерировалось, прежде чем показывать выводы:\n' +
          '```look ' + path + '\nчто на картинке? опиши точно\n```\n' +
          'Секунду.';
      } else {
        text =
          'Смотрела: варианты на месте, стиль выдержан. Выбирайте номер — выбранный возьму референсом ' +
          'и дорисую в высоком разрешении или поправлю по вашим правкам.';
      }
    } else if (!this.fixedReply && (req.system ?? '').includes('```file')) {
      // демо инструментов: у агента в промпте есть блок ```file — показываем протокол в деле.
      // По числу результатов в истории ступеньки: файл → команда → итог (детерминированно для тестов).
      const steps = req.messages.filter((m) => m.content.includes('⚙ Результаты твоих действий')).length;
      if (steps === 0) {
        text = 'Так, это я могу не на словах. Держи стартовый файл:\n```file demo-agent.txt\nПривет от mock-агента: инструменты реально работают.\nВторая строка — для порядка.\n```\nЗаписал, дальше по обстановке.';
      } else if (steps === 1 && (req.system ?? '').includes('```run')) {
        text = 'Теперь проверю окружение одной командой:\n```run\necho инструменты-работают\n```\nСекунду, гляну вывод.';
      } else {
        text = 'Результаты видел в истории, всё на месте. Продолжаем.';
      }
    }
    for (const token of text.split(/(?<=\s)/)) {
      if (req.signal?.aborted) return; // раунд прерван (Esc)
      await sleep(this.delayMs);
      yield token;
    }
    // синтетическая статистика без попаданий в кэш: упражняет путь onUsage
    // в пробах, а заметку о кэше в mock-режиме рисовать не о чем
    onUsage?.({
      promptTokens: 400,
      cachedTokens: 0,
      outputTokens: Math.ceil(text.length / 4),
    });
  }
}

/** Адаптер "mock" — можно назначить провайдеру в providers.json явно. */
export const mockFactory: ProviderFactory = (id, config: ProviderConfig) => {
  const note = typeof config.note === 'string' ? config.note : undefined;
  const model = typeof config.model === 'string' ? config.model : 'mock';
  return new MockProvider(id, model, note);
};

/** Провайдер, у которого не хватает настроек/ключа: честно объясняет это вместо ответа. */
export function unconfiguredProvider(id: string, reason: string): LLMProvider {
  return new MockProvider(
    id,
    'mock',
    `⚠️ Провайдер «${id}» не настроен: ${reason}\nВпишите ключ в .env (см. README) — и участник начнёт отвечать по-настоящему.`,
    10,
  );
}
